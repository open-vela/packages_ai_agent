/* ── Render thread ─────────────────────────────────────────────── */

static void ui_build(void)
{
    int W = lv_display_get_horizontal_resolution(NULL);
    int H = lv_display_get_vertical_resolution(NULL);

    syslog(LOG_INFO, "[%s] build UI on %dx%d display\n", UI_TAG, W, H);

    s_ui.screen = lv_screen_active();
    lv_obj_set_style_bg_color(s_ui.screen, lv_color_hex(CLR_BG), 0);

    s_ui.font = &ui_font_cjk_18;
    s_ui.font_big = s_ui.font;

    bubble_widget_create();
    menu_btn_create();
    history_page_create();

    if (pet_display_init(s_ui.screen) != 0) {
        syslog(LOG_ERR, "[%s] pet_display_init failed\n", UI_TAG);
    }

    /* tap the pet to toggle the head bubble */
    lv_obj_add_flag(pet_display_get_obj(), LV_OBJ_FLAG_CLICKABLE);
    lv_obj_add_event_cb(pet_display_get_obj(), pet_click_cb,
                        LV_EVENT_CLICKED, NULL);
    lv_obj_move_foreground(pet_display_get_obj());

    /* Launcher desktop on top: app icons → pet / settings pages */
    launcher_create();
    lv_obj_move_foreground(launcher_desktop_obj());

    /* The desktop is opaque and covers the whole screen, so the pet stage
     * below it can never be seen -- but LVGL culls invalidation only for
     * LV_OBJ_FLAG_HIDDEN objects, never for ones merely covered by a sibling.
     * Left visible, the pet's idle float animation invalidated its 300x300
     * area every refresh period and dragged a full-screen repaint with it.
     * Also hide the menu button for the same reason.
     */

    pet_display_set_stage_visible(false);
    if (s_ui.menu_btn) {
        lv_obj_add_flag(s_ui.menu_btn, LV_OBJ_FLAG_HIDDEN);
    }

    syslog(LOG_INFO, "[%s] launcher desktop created\n", UI_TAG);
}

/* ── Render thread ─────────────────────────────────────────────── */

static void *render_thread(void *arg)
{
    (void)arg;

    ui_build();

    while (s_ui.running) {
        lv_timer_handler();
        usleep(RENDER_PERIOD_US);
    }
    return NULL;
}

