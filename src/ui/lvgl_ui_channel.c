    lv_obj_t *btn;
    lv_obj_t *bar;
    int W = lv_display_get_horizontal_resolution(NULL);
    int i;

    btn = lv_obj_create(s_ui.screen);
    lv_obj_set_size(btn, 60, 60);
    lv_obj_align(btn, LV_ALIGN_TOP_RIGHT, -24, BUBBLE_TOP_Y);
    lv_obj_set_style_radius(btn, LV_RADIUS_CIRCLE, 0);
