/* ── Chat history persistence (DEMO-HIST) ──────────────────────
 * RAM 环只有 CHAT_HISTORY_MAX(20) 条，重启就丢；这里把最近
 * HIST_FILE_KEEP(100) 条落到 /data/ai_agent/chat_history.dat，启动时再灌回
 * 环 —— 于是 ui hist / 历史浮层 / App chat_history 都能看到重启前的记录。
 *
 * 文件格式：一行一条，旧→新：
 *   U<TAB><转义后的用户文本>
 *   A<TAB><转义后的回答文本>
 * 只转义 \、\n、\r、\t，保证"一条记录=一行"；加载时非法行/损坏行直接
 * 跳过（corruption-safe），不会阻塞启动。
 *
 * I/O 纪律（不阻塞 LVGL 渲染线程过久）：
 *  - history_add() 只置 dirty + 时间戳（渲染线程，零 I/O）；
 *  - 渲染循环里的 history_store_tick() 节流：最后一次 add 后
 *    HIST_FLUSH_DEBOUNCE_MS(500ms) 才落盘（连续消息合并成一次），最长延迟
 *    HIST_FLUSH_MAXDELAY_MS(2500ms)；
 *  - 每次只 APPEND 新增的 1~2 行（littlefs 小写，典型 <2KB），不做每消息
 *    全量重写；文件超过 HIST_FILE_KEEP 行时才整理一次（tmp + rename）。
 *  - 加载只在 lvgl_ui_channel_init() 里做一次（渲染线程启动前，无需加锁）。
 * 说明：/data/ai_agent 由 config_store 启动早期创建；这里仍对 ENOENT 做一次
 * mkdir 兜底。写失败只记一条 warning 并保留 dirty，下个节流周期重试。
 */
#define HIST_FILE          AGENT_DATA_DIR "/chat_history.dat"
#define HIST_FILE_TMP      AGENT_DATA_DIR "/chat_history.tmp"
#define HIST_FILE_KEEP     100      /* 文件保留最近 100 条（任务要求 50-100） */
#define HIST_FLUSH_DEBOUNCE_MS  500
#define HIST_FLUSH_MAXDELAY_MS 2500
#define HIST_LINE_MAX      (MSG_MAX_LEN * 2 + 16)
#define HIST_LOAD_MAX_LINES 8192    /* 损坏/异常大文件的加载上限 */

static struct {
    bool     dirty;        /* 有未落盘的新记录 */
    bool     loaded;       /* 本次 boot 已尝试加载过 */
    bool     need_compact; /* 上次整理失败，稍后重试 */
    bool     file_warned;  /* 首次 I/O 失败已告警（避免刷屏） */
    uint32_t dirty_since;  /* 第一条未落盘记录的 tick */
    uint32_t last_add;     /* 最近一次 add/I/O 尝试的 tick（节流用） */
    int      pending;      /* 尚未落盘的记录条数（>MAX 说明环已覆盖，需重写） */
    int      file_lines;   /* 文件行数（append 递增 / 整理后校准） */
} s_hist_store;

/* 环形缓冲插入（不置持久化标记；加载历史与运行时共用） */
static void history_ring_put(const char *text, bool is_user)
{
    chat_msg_t *slot = &s_history.msgs[s_history.head];

    memset(slot, 0, sizeof(*slot));
    strncpy(slot->text, text, MSG_MAX_LEN - 1);
    slot->text[MSG_MAX_LEN - 1] = '\0';
    slot->is_user = is_user;

    s_history.head = (s_history.head + 1) % CHAT_HISTORY_MAX;
    if (s_history.count < CHAT_HISTORY_MAX) {
        s_history.count++;
    }
}

static void history_mark_dirty(void)
{
    uint32_t now = lv_tick_get();

    if (!s_hist_store.dirty) {
        s_hist_store.dirty = true;
        s_hist_store.dirty_since = now;
    }
    /* 记录条数用独立计数器而不是"head 差"：环回绕后 head 差会算出旧位置，
     * 导致把最旧的几条写进文件（首 boot 连续 25 条就会踩到）。 */
    if (s_hist_store.pending < CHAT_HISTORY_MAX * 2) {
        s_hist_store.pending++;
    }
    s_hist_store.last_add = now;
}

static void history_add(const char *text, bool is_user)
{
    history_ring_put(text, is_user);
    history_mark_dirty();
}

int lvgl_ui_history_count(void)
{
    return s_history.count;
}

bool lvgl_ui_history_get(int newest_first, char *buf, size_t len,
                        bool *is_user)
{
    const chat_msg_t *m;
    int idx;

    /* Callers run on the LVGL thread (pet page, history page), the same
     * thread history_add() is reached from via lv_async_call, so the ring
     * needs no lock. */

    if (!buf || len == 0 || newest_first < 0 ||
        newest_first >= s_history.count) {
        return false;
    }

    idx = (s_history.head - 1 - newest_first + 2 * CHAT_HISTORY_MAX)
          % CHAT_HISTORY_MAX;
    m = &s_history.msgs[idx];

    strncpy(buf, m->text, len - 1);
    buf[len - 1] = '\0';
    if (is_user) {
        *is_user = m->is_user;
    }
    return true;
}

/* 转义：把一条消息压成单行（\\、\n、\r、\t 转成字面量） */
static size_t hist_escape(const char *src, char *dst, size_t cap)
{
    size_t o = 0;
    const char *p;

    if (cap == 0) {
        return 0;
    }
    for (p = src; *p != '\0'; p++) {
        const char *rep;
        char one[2];
        size_t n;

        switch (*p) {
        case '\\': rep = "\\\\"; break;
        case '\n': rep = "\\n"; break;
        case '\r': rep = "\\r"; break;
        case '\t': rep = "\\t"; break;
        default:
            one[0] = *p;
            one[1] = '\0';
            rep = one;
            break;
        }
        n = strlen(rep);
        if (o + n >= cap) {
            break;   /* 截断保护：宁可少写也不越界 */
        }
        memcpy(dst + o, rep, n);
        o += n;
    }
    dst[o] = '\0';
    return o;
}

/* 反转义（就地）；未知转义保留反斜杠本身 */
static void hist_unescape(char *s)
{
    char *w = s;
    char *r = s;

    while (*r != '\0') {
        if (*r == '\\' && r[1] != '\0') {
            switch (r[1]) {
            case '\\': *w++ = '\\'; r += 2; break;
            case 'n':  *w++ = '\n'; r += 2; break;
            case 'r':  *w++ = '\r'; r += 2; break;
            case 't':  *w++ = '\t'; r += 2; break;
            default:
                *w++ = *r++;
                break;
            }
        } else {
            *w++ = *r++;
        }
    }
    *w = '\0';
}

static int hist_ensure_dir(void)
{
    if (mkdir(AGENT_DATA_DIR, 0700) == 0 || errno == EEXIST) {
        return 0;
    }
    return -errno;
}

static void hist_log_io_fail(const char *what, int err)
{
    if (!s_hist_store.file_warned) {
        s_hist_store.file_warned = true;
        syslog(LOG_WARNING,
            "[%s] chat history %s failed: %d (will retry)\n",
            UI_TAG, what, err);
    }
}

/* /data/ai_agent 不存在时兜底建一次目录（config_store 本来就会建） */
static FILE *hist_open(const char *path, const char *mode)
{
    FILE *fp = fopen(path, mode);

    if (fp == NULL && errno == ENOENT && hist_ensure_dir() == 0) {
        fp = fopen(path, mode);
    }
    return fp;
}

/* 追加"自上次成功落盘以来"的新记录；返回追加行数，负数=失败 */
static int hist_append(char *line)
{
    FILE *fp;
    int pending = s_hist_store.pending;
    int start;
    int i;
    int written = 0;
    int ferr;

    if (pending == 0) {
        return 0;
    }
    /* pending > 环容量：那几条已经被环形缓冲覆盖，无法按序补写 → 整体重写 */
    if (pending > s_history.count) {
        return -ERANGE;
    }

    start = (s_history.head - pending + 2 * CHAT_HISTORY_MAX) % CHAT_HISTORY_MAX;

    fp = hist_open(HIST_FILE, "a");
    if (fp == NULL) {
        hist_log_io_fail("open", errno);
        return -1;
    }

    for (i = 0; i < pending; i++) {
        const chat_msg_t *m = &s_history.msgs[(start + i) % CHAT_HISTORY_MAX];

        hist_escape(m->text, line, HIST_LINE_MAX);
        if (fputs(m->is_user ? "U\t" : "A\t", fp) == EOF
            || fputs(line, fp) == EOF
            || fputc('\n', fp) == EOF) {
            break;
        }
        written++;
    }
    ferr = fclose(fp);

    if (written != pending || ferr != 0) {
        hist_log_io_fail("append", errno);
        return -1;
    }

    s_hist_store.pending = 0;
    s_hist_store.file_lines += written;
    return written;
}

/* 用当前 RAM 环（最多 20 条）整体重写文件（tmp + rename，原子） */
static int hist_rewrite_ring(char *line)
{
    FILE *fp;
    int idx;
    int i;
    int n = 0;
    int ferr;

    fp = hist_open(HIST_FILE_TMP, "w");
    if (fp == NULL) {
        hist_log_io_fail("open tmp", errno);
        return -1;
    }
    idx = (s_history.head - s_history.count + CHAT_HISTORY_MAX)
          % CHAT_HISTORY_MAX;
    for (i = 0; i < s_history.count; i++) {
        const chat_msg_t *m = &s_history.msgs[idx];

        hist_escape(m->text, line, HIST_LINE_MAX);
        if (fputs(m->is_user ? "U\t" : "A\t", fp) == EOF
            || fputs(line, fp) == EOF
            || fputc('\n', fp) == EOF) {
            break;
        }
        n++;
        idx = (idx + 1) % CHAT_HISTORY_MAX;
    }
    ferr = fclose(fp);

    if (n != s_history.count || ferr != 0) {
        hist_log_io_fail("rewrite", errno);
        remove(HIST_FILE_TMP);
        return -1;
    }
    if (rename(HIST_FILE_TMP, HIST_FILE) != 0) {
        hist_log_io_fail("rename", errno);
        remove(HIST_FILE_TMP);
        return -1;
    }
    s_hist_store.pending = 0;
    s_hist_store.file_lines = n;
    return n;
}

/* 只保留文件里最新 HIST_FILE_KEEP 行（两遍扫描，行缓冲由调用方提供） */
static int hist_compact(char *line)
{
    FILE *in;
    FILE *out;
    int total = 0;
    int skip;
    int kept = 0;
    int ferr;

    in = fopen(HIST_FILE, "r");
    if (in == NULL) {
        return -1;
    }
    while (fgets(line, HIST_LINE_MAX, in) != NULL) {
        total++;
    }
    if (total <= HIST_FILE_KEEP) {
        fclose(in);
        s_hist_store.file_lines = total;
        return 0;
    }
    rewind(in);
    out = hist_open(HIST_FILE_TMP, "w");
    if (out == NULL) {
        fclose(in);
        hist_log_io_fail("open tmp", errno);
        return -1;
    }
    skip = total - HIST_FILE_KEEP;
    while (fgets(line, HIST_LINE_MAX, in) != NULL) {
        if (skip > 0) {
            skip--;
            continue;
        }
        if (fputs(line, out) == EOF) {
            break;
        }
        kept++;
    }
    ferr = fclose(in);
    if (out != NULL) {
        ferr |= fclose(out);
    }

    if (kept != HIST_FILE_KEEP || ferr != 0) {
        hist_log_io_fail("compact write", errno);
        remove(HIST_FILE_TMP);
        return -1;
    }
    if (rename(HIST_FILE_TMP, HIST_FILE) != 0) {
        hist_log_io_fail("rename", errno);
        remove(HIST_FILE_TMP);
        return -1;
    }
    s_hist_store.file_lines = kept;
    return 0;
}

/* 节流落盘：只在 dirty / need_compact 时由 tick 调用 */
static void history_store_flush(void)
{
    char *line = malloc(HIST_LINE_MAX);

    if (line == NULL) {
        hist_log_io_fail("alloc", ENOMEM);
        s_hist_store.last_add = lv_tick_get();
        return;
    }

    if (s_hist_store.dirty) {
        int appended = hist_append(line);

        if (appended == -ERANGE) {
            syslog(LOG_WARNING,
                "[%s] chat history: ring wrapped before flush, rewrite\n",
                UI_TAG);
            appended = hist_rewrite_ring(line);
        }
        if (appended < 0) {
            /* 保留 dirty，下个节流周期重试（失败日志只由 hist_log_io_fail 打一条） */
            s_hist_store.last_add = lv_tick_get();
            s_hist_store.dirty_since = s_hist_store.last_add;
            free(line);
            return;
        }
        s_hist_store.dirty = false;
        syslog(LOG_DEBUG, "[%s] chat history flush: +%d line(s), total=%d\n",
            UI_TAG, appended, s_hist_store.file_lines);
    }

    if (s_hist_store.file_lines > HIST_FILE_KEEP) {
        uint32_t t0 = lv_tick_get();

        if (hist_compact(line) == 0) {
            s_hist_store.need_compact = false;
            syslog(LOG_INFO,
                "[%s] chat history compacted to %d lines (%lums)\n",
                UI_TAG, s_hist_store.file_lines,
                (unsigned long)(lv_tick_get() - t0));
        } else {
            s_hist_store.need_compact = true;
        }
    }

    s_hist_store.last_add = lv_tick_get();
    free(line);
}

/* 渲染循环每 ~5ms 调一次；绝大多数 tick 只走"两个 bool"快路，零 I/O */
static void history_store_tick(void)
{
    uint32_t now;

    if (!s_hist_store.dirty && !s_hist_store.need_compact) {
        return;
    }
    now = lv_tick_get();

    /* 防抖：最后一次 add 后 500ms 才写；最长延迟 2500ms 防止一直等 */
    if (s_hist_store.dirty
        && (uint32_t)(now - s_hist_store.last_add) < HIST_FLUSH_DEBOUNCE_MS
        && (uint32_t)(now - s_hist_store.dirty_since) < HIST_FLUSH_MAXDELAY_MS) {
        return;
    }
    /* 仅整理重试（无新记录）时也按 MAXDELAY 节流 */
    if (!s_hist_store.dirty
        && (uint32_t)(now - s_hist_store.last_add) < HIST_FLUSH_MAXDELAY_MS) {
        return;
    }
    history_store_flush();
}

/* 启动时加载一次（lvgl_ui_channel_init 里、渲染线程启动前调用，无需加锁） */
static void history_store_load(void)
{
    FILE *fp;
    char *line;
    int total = 0;
    int used = 0;

    if (s_hist_store.loaded) {
        return;
    }
    s_hist_store.loaded = true;

    fp = fopen(HIST_FILE, "r");
    if (fp == NULL) {
        syslog(LOG_INFO, "[%s] chat history: no file yet (%s)\n",
            UI_TAG, HIST_FILE);
        return;
    }
    line = malloc(HIST_LINE_MAX);
    if (line == NULL) {
        fclose(fp);
        hist_log_io_fail("alloc", ENOMEM);
        return;
    }

    while (fgets(line, HIST_LINE_MAX, fp) != NULL) {
        size_t n;

        if (++total > HIST_LOAD_MAX_LINES) {
            syslog(LOG_WARNING,
                "[%s] chat history: file too long, load truncated\n", UI_TAG);
            break;
        }
        n = strlen(line);
        while (n > 0 && (line[n - 1] == '\n' || line[n - 1] == '\r')) {
            line[--n] = '\0';
        }
        /* 损坏/未知行直接忽略（corruption-safe，不阻塞启动） */
        if (n < 3 || (line[0] != 'U' && line[0] != 'A') || line[1] != '\t') {
            continue;
        }
        hist_unescape(line + 2);
        if (line[2] == '\0') {
            continue;
        }
        history_ring_put(line + 2, line[0] == 'U');
        used++;
    }
    fclose(fp);
    s_hist_store.file_lines = total;
    /* 文件里已经包含这些记录：加载不算"待落盘" */
    s_hist_store.pending = 0;
    syslog(LOG_INFO,
        "[%s] chat history loaded: %d line(s), %d record(s), ring=%d/%d\n",
        UI_TAG, total, used, s_history.count, CHAT_HISTORY_MAX);

    if (total > HIST_FILE_KEEP) {
        if (hist_compact(line) == 0) {
            syslog(LOG_INFO, "[%s] chat history trimmed to %d lines at boot\n",
                UI_TAG, s_hist_store.file_lines);
        } else {
            s_hist_store.need_compact = true;
        }
    }
    free(line);
}

