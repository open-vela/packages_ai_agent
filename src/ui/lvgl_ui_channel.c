/*
 * lvgl_ui_channel.c - Pet UI channel for the AI Agent.
 *
 * Self-contained LVGL display stack for boards WITHOUT a miwear
 * environment: lv_init() + lv_nuttx_init() (framebuffer /dev/lcd0,
 * touch /dev/input0) + a dedicated render thread running
 * lv_timer_handler().
 *
 * UI layout (stage):
 *   - cloud mascot centered (pet_display.c), tap toggles the bubble
 *   - head bubble above the pet showing the latest message
 *   - message menu button (top-right) opens the full history page
 *
 * External interface (init/start/stop/show/send) is unchanged so the
 * agent core (agent_main.c, outbound dispatch) keeps working.
 */

