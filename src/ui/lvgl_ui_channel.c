/* ── Streaming answer display (SPEED-B, v125) ─────────────────
 *
 * 目标：LLM 边生成边把文字写到头顶气泡 + 桌宠页 AI 文本层，而不是等整句
 * 回来才出现。4 个 API 由 LLM 流式层从**任意线程**调用：内部只做
 * malloc + lvgl_ui_post() 入队，真正的 lv_obj 操作全部在 render 线程，
 * 调用线程绝不直接碰 LVGL（LVGL 以 LV_OS_NONE 构建，见上面 lvgl_ui_post 注释）。
 *
 * 状态划分：
 *   - s_stream（caller 侧）：只被公开函数读写，s_stream_lock 保护；
 *     只有 bool/int 标量，不持有任何 LVGL 对象或大缓冲。
 *   - s_stream_ui（LVGL 线程侧）：只在 posted 回调里读写，持有增量文本
 *     （begin 时 malloc MSG_MAX_LEN 字节，end/abort 释放；无静态大数组）。
 *   - 历史环 / 桌宠页文本层沿用原有“只在 LVGL 线程写”的约束。
 *
 * 与 dispatch 镜像的零重复：end 已经把最终回答写进历史/桌宠页/气泡，而
 * agent_main 随后仍会按原通道镜像再调 lvgl_ui_channel_log() 或
 * queue_agent_bubble()。这两处在写历史前先问一次 s_stream_dedup（end 时
 * armed，命中即销账，8 s TTL 兜底），所以同一句只落一次；调用方无需关心。
 *
 * delta 是 best-effort：积压超过 STREAM_MAX_PENDING_DELTAS 或内存不足时
 * 丢增量（只记一次日志）；end 不走该背压，final 文本永远单独入队。
 */

#define STREAM_THINKING_TEXT       "小云思考中…"
#define STREAM_MAX_PENDING_DELTAS  16
#define STREAM_DEDUP_TTL_MS        8000

typedef struct {
    char *user_text;              /* heap copy, may be NULL */
} stream_begin_msg_t;

typedef struct {
    char *final_text;             /* heap copy, never NULL ("") */
    bool  from_local;
} stream_end_msg_t;

/* caller 侧（任意线程）状态，s_stream_lock 保护 */
static pthread_mutex_t s_stream_lock = PTHREAD_MUTEX_INITIALIZER;
static struct {
    bool begun;
    int  pending_deltas;
    bool drop_logged;
} s_stream;

/* LVGL 线程侧状态：只在 posted 回调里访问 */
static struct {
    char  *text;             /* heap，MSG_MAX_LEN 字节，begin 分配/end|abort 释放 */
    size_t len;
    bool   active;
    bool   bubble_was_hidden; /* 本轮 begin/delta 把气泡从隐藏变可见 -> abort 时收回 */
    bool   cap_logged;
    int    deltas;            /* 已显示增量条数（abort 日志/行为判断用） */
} s_stream_ui;

/* end 落历史后的一次性镜像去重（LVGL 线程侧） */
static struct {
    bool     armed;
    uint32_t hash_a;          /* hash(display)：带 “（本地）” 的镜像文本 */
    uint32_t hash_b;          /* hash(final_text)：不带标记的镜像文本 */
    uint32_t arm_tick;
} s_stream_dedup;

static uint32_t stream_hash(const char *s)
{
    uint32_t h = 2166136261u;

    if (s == NULL) {
        return 0;
    }
    while (*s != '\0') {
        h ^= (uint8_t)*s++;
        h *= 16777619u;
    }
    return h;
}

/* 返回 [0,n) 内**完整** UTF-8 字符的前缀字节数：尾部半个字符不算。
 * delta 由流式层保证整串合法，这里只是防御（万一 SSE 分片切在字符中间，
 * 也不能把半个字符写进 label 或截断到内存里）。 */
static size_t stream_utf8_complete_len(const char *s, size_t n)
{
    size_t i = 0;

    while (i < n) {
        unsigned char c = (unsigned char)s[i];
        size_t need;

        if (c < 0x80) {
            need = 1;
        } else if ((c & 0xE0) == 0xC0) {
            need = 2;
        } else if ((c & 0xF0) == 0xE0) {
            need = 3;
        } else if ((c & 0xF8) == 0xF0) {
            need = 4;
        } else {
            need = 1;         /* 非法首字节：当单字节处理，不卡住 */
        }
        if (i + need > n) {
            break;            /* 尾部不完整 */
        }
        i += need;
    }
    return i;
}

/* 把流式累计文本写进头顶气泡（同一气泡、只 set_text）。
 * 超过气泡容量时显示**尾部**（前缀 …）而不是头部：长回答如果只显示开头，
 * 132 字节之后气泡看起来就“卡住不动”了，流式感会消失。 */
static void bubble_set_stream_text(const char *text, size_t len)
{
    char disp[BUBBLE_MAX_CHARS + 4];
    size_t complete = stream_utf8_complete_len(text, len);
    size_t start = 0;
    size_t n;
    size_t out = 0;

    if (complete > BUBBLE_MAX_CHARS) {
        start = complete - (BUBBLE_MAX_CHARS - 3);  /* 3 字节留给前缀 … */
        while (start < complete
               && ((unsigned char)text[start] & 0xC0) == 0x80) {
            start++;                                /* 退到字符边界 */
        }
        memcpy(disp, "\xe2\x80\xa6", 3);          /* … */
        out = 3;
    }

    n = complete - start;
    if (n > (size_t)BUBBLE_MAX_CHARS - out) {
        n = (size_t)BUBBLE_MAX_CHARS - out;
        while (n > 0 && ((unsigned char)text[start + n] & 0xC0) == 0x80) {
            n--;
        }
    }
    memcpy(disp + out, text + start, n);
    out += n;
    disp[out] = '\0';

    bubble_set_text(disp);
}

/* LVGL 线程：清流式状态。hide_bubble=true 时把本轮弹出来的气泡收回。 */
static void stream_ui_reset(bool hide_bubble)
{
    free(s_stream_ui.text);
    s_stream_ui.text = NULL;
    s_stream_ui.len = 0;
    s_stream_ui.active = false;
    s_stream_ui.cap_logged = false;
    s_stream_ui.deltas = 0;

    if (hide_bubble && s_stream_ui.bubble_was_hidden
        && s_ui.bubble != NULL && s_ui.bubble_visible) {
        bubble_hide_anim();
    }
    s_stream_ui.bubble_was_hidden = false;
}

/* end 之后，dispatch 镜像文本是否应该被跳过（同一句只落一次历史）。
 * 只有在 end 刚落地（armed）且 8s 内、且文本与 end 写入的两种形态之一
 * 完全一致时才跳过；任何别的回答都不受影响。 */
static bool stream_dedup_should_skip(const char *text, bool is_user)
{
    uint32_t h;

    if (!s_stream_dedup.armed || is_user || text == NULL) {
        return false;
    }
    if ((uint32_t)(lv_tick_get() - s_stream_dedup.arm_tick)
        > STREAM_DEDUP_TTL_MS) {
        s_stream_dedup.armed = false;
        return false;
    }

    h = stream_hash(text);
    if (h == s_stream_dedup.hash_a || h == s_stream_dedup.hash_b) {
        s_stream_dedup.armed = false;
        syslog(LOG_INFO, "[%s] stream dedup: mirrored final suppressed\n",
               UI_TAG);
        return true;
    }
    return false;
}

/* begin 落地：用户问题入历史/气泡（ASR 已显示则复用），占位“思考中”。 */
static void stream_begin_async_cb(void *data)
{
    stream_begin_msg_t *m = (stream_begin_msg_t *)data;
    const char *user = (m != NULL) ? m->user_text : NULL;

    if (!s_ui.initialized || !s_ui.running) {
        goto out;
    }

    stream_ui_reset(false);    /* 重复 begin：重置上一条未结束的流 */

    if (user != NULL && user[0] != '\0') {
        char last[MSG_MAX_LEN];
        bool last_is_user = false;
        bool dup = false;

        if (lvgl_ui_history_get(0, last, sizeof(last), &last_is_user)
            && last_is_user && strcmp(last, user) == 0) {
            dup = true;        /* ASR/ask/BLE 已经把这条用户问题显示过：复用 */
        }
        if (!dup) {
            history_add(user, true);
            if (s_ui.history_visible) {
                history_rebuild_list();
            }
        }
        /* 用户问题也上头顶气泡（与 lvgl_ui_channel_send_user 的视觉一致） */
        if (s_ui.bubble != NULL && s_ui.bubble_label != NULL) {
            bubble_set_text(user);
            lv_obj_set_style_bg_color(s_ui.bubble,
                lv_color_hex(CLR_BUBBLE_USER), 0);
            if (s_ui.bubble_tail != NULL) {
                lv_obj_set_style_bg_color(s_ui.bubble_tail,
                    lv_color_hex(CLR_BUBBLE_USER), 0);
            }
            if (!s_ui.bubble_visible) {
                bubble_show_anim();
                s_stream_ui.bubble_was_hidden = true;
            }
        }
    }

    s_stream_ui.text = malloc(MSG_MAX_LEN);
    if (s_stream_ui.text != NULL) {
        s_stream_ui.text[0] = '\0';
    }
    s_stream_ui.len = 0;
    s_stream_ui.active = true;
    s_stream_ui.cap_logged = false;
    s_stream_ui.deltas = 0;

    /* 2026-11-03：流式增量必须让用户看见。最终回答的 history_log_async_cb
     * 在表盘页会自动 nav 到 UI_PAGE_AI；流式 begin 之前没有这一步，于是
     * 表盘页用户只看到最终答案、看不到边生成边出字。这里与最终路径对齐。 */
    if (ui_nav_current() == UI_PAGE_WATCHFACE) {
        ui_nav_goto(UI_PAGE_AI);
    }

    /* 占位放在桌宠页 AI 文本层；头顶气泡先留给用户问题，第一个 delta
     * 到达时再切到答案（同一气泡追加）。 */
    pet_page_update_response(STREAM_THINKING_TEXT);
    pet_display_set_emotion(PET_EMOTION_THINKING);

    syslog(LOG_INFO, "[%s] stream begin: user=\"%.40s\"\n",
           UI_TAG, (user != NULL) ? user : "");

out:
    if (m != NULL) {
        free(m->user_text);
        free(m);
    }
}

/* delta 落地：追加到同一气泡 + 桌宠页文本层（不重建页面/不写历史）。 */
static void stream_delta_async_cb(void *data)
{
    char *delta = (char *)data;
    size_t dlen;
    size_t avail;
    size_t take;

    pthread_mutex_lock(&s_stream_lock);
    if (s_stream.pending_deltas > 0) {
        s_stream.pending_deltas--;
    }
    pthread_mutex_unlock(&s_stream_lock);

    if (delta == NULL) {
        return;
    }
    if (!s_ui.initialized || !s_ui.running || !s_stream_ui.active) {
        free(delta);
        return;
    }

    if (s_stream_ui.text == NULL) {
        s_stream_ui.text = malloc(MSG_MAX_LEN);
        if (s_stream_ui.text == NULL) {
            free(delta);
            return;
        }
        s_stream_ui.text[0] = '\0';
        s_stream_ui.len = 0;
    }

    dlen = strlen(delta);
    avail = (MSG_MAX_LEN - 1) - s_stream_ui.len;
    if (dlen > avail) {
        take = avail;
        while (take > 0 && ((unsigned char)delta[take] & 0xC0) == 0x80) {
            take--;                           /* 丢也丢在字符边界上 */
        }
        if (!s_stream_ui.cap_logged) {
            syslog(LOG_WARNING,
                "[%s] stream text cap %d reached, dropping tail\n",
                UI_TAG, MSG_MAX_LEN - 1);
            s_stream_ui.cap_logged = true;
        }
    } else {
        take = dlen;
    }
    if (take > 0) {
        memcpy(s_stream_ui.text + s_stream_ui.len, delta, take);
        s_stream_ui.len += take;
        s_stream_ui.text[s_stream_ui.len] = '\0';
        s_stream_ui.deltas++;
    }
    free(delta);

    if (s_stream_ui.len == 0 || s_ui.bubble == NULL
        || s_ui.bubble_label == NULL) {
        return;
    }

    bubble_set_stream_text(s_stream_ui.text, s_stream_ui.len);
    lv_obj_set_style_bg_color(s_ui.bubble, lv_color_hex(CLR_BUBBLE_PET), 0);
    if (s_ui.bubble_tail != NULL) {
        lv_obj_set_style_bg_color(s_ui.bubble_tail,
            lv_color_hex(CLR_BUBBLE_PET), 0);
    }
    if (!s_ui.bubble_visible) {
        bubble_show_anim();
        s_stream_ui.bubble_was_hidden = true;
    }
    pet_page_update_response(s_stream_ui.text);
}

/* end 落地：最终回答写历史/桌宠页文本层/气泡（“（本地）”标记与 ui_mirror
 * 一致），并 arm 一次性去重挡掉随后 dispatch 镜像的同一句。 */
static void stream_end_async_cb(void *data)
{
    stream_end_msg_t *m = (stream_end_msg_t *)data;
    const char *final_text = (m != NULL && m->final_text != NULL)
                                 ? m->final_text : "";
    bool from_local = (m != NULL) ? m->from_local : false;
    char display[MSG_MAX_LEN];
    size_t n;

    if (!s_ui.initialized || !s_ui.running) {
        goto out;
    }

    /* 来源标记：与 agent_main 的 ui_mirror_answer() 完全一致 */
    n = strlen(final_text);
    if (from_local) {
        size_t room = sizeof(display) - sizeof("（本地）");

        if (n > room) {
            n = room;
            while (n > 0 && ((unsigned char)final_text[n] & 0xC0) == 0x80) {
                n--;
            }
        }
        memcpy(display, final_text, n);
        memcpy(display + n, "（本地）", sizeof("（本地）"));
    } else {
        if (n > sizeof(display) - 1) {
            n = sizeof(display) - 1;
            while (n > 0 && ((unsigned char)final_text[n] & 0xC0) == 0x80) {
                n--;
            }
        }
        memcpy(display, final_text, n);
        display[n] = '\0';
    }

    /* 1) 历史环 + 桌宠页文本层（语义等价 lvgl_ui_channel_log(display,false)） */
    history_add(display, false);
    pet_page_update_response(display);
    if (s_ui.history_visible) {
        history_rebuild_list();
    }

    /* 2) 最终气泡：换成完整回答（与现有 bubble 一样的头截断规则） */
    if (s_ui.bubble != NULL && s_ui.bubble_label != NULL) {
        bubble_set_text(display);
        lv_obj_set_style_bg_color(s_ui.bubble,
            lv_color_hex(CLR_BUBBLE_PET), 0);
        if (s_ui.bubble_tail != NULL) {
            lv_obj_set_style_bg_color(s_ui.bubble_tail,
                lv_color_hex(CLR_BUBBLE_PET), 0);
        }
        if (!s_ui.bubble_visible) {
            bubble_show_anim();
        }
    }

    /* 3) 表情：与 lvgl_ui_channel_send_kind() 的 FINAL 分支一致（只是表演） */
    {
        pet_emotion_t emo = emotion_from_text(display);

        pet_display_set_emotion(emo);
        pet_back_idle_after(emo == PET_EMOTION_SPEAKING ? 4000 : 1500);
    }

    /* 4) 表盘上收到回答 -> 自动切 AI 页；其它页面不打断（与 log 回调一致） */
    if (ui_nav_current() == UI_PAGE_WATCHFACE) {
        ui_nav_goto(UI_PAGE_AI);
    }

    stream_ui_reset(false);

    /* 5) arm 一次性去重：dispatch 镜像会在之后写同一句（带/不带“（本地）”）*/
    s_stream_dedup.armed = true;
    s_stream_dedup.hash_a = stream_hash(display);
    if (from_local) {
        char plain[MSG_MAX_LEN];

        n = strlen(final_text);
        if (n > sizeof(plain) - 1) {
            n = sizeof(plain) - 1;
            while (n > 0 && ((unsigned char)final_text[n] & 0xC0) == 0x80) {
                n--;
            }
        }
        memcpy(plain, final_text, n);
        plain[n] = '\0';
        s_stream_dedup.hash_b = stream_hash(plain);
    } else {
        s_stream_dedup.hash_b = s_stream_dedup.hash_a;
    }
    s_stream_dedup.arm_tick = lv_tick_get();

    syslog(LOG_INFO, "[%s] stream end: %d bytes\n",
           UI_TAG, (int)strlen(display));

out:
    if (m != NULL) {
        free(m->final_text);
        free(m);
    }
}

/* abort 落地：清占位/半成品；历史里只留随后 dispatch 的错误语。 */
static void stream_abort_async_cb(void *data)
{
    (void)data;

    if (!s_ui.initialized || !s_ui.running) {
        stream_ui_reset(false);
        return;
    }
    if (!s_stream_ui.active) {
        return;                       /* 没有 begin 过：无事可清 */
    }

    if (s_stream_ui.deltas == 0) {
        /* 还只有占位：清气泡文本，让桌宠页恢复到 greeting */
        if (s_ui.bubble != NULL && s_ui.bubble_label != NULL) {
            bubble_set_text("");
        }
        pet_page_schedule_greeting_restore(1200);
    }
    pet_display_set_emotion(PET_EMOTION_IDLE);
    syslog(LOG_INFO, "[%s] stream abort (deltas=%d)\n",
           UI_TAG, s_stream_ui.deltas);
    stream_ui_reset(true);
}

int lvgl_ui_channel_stream_begin(const char *user_text)
{
    stream_begin_msg_t *m;

    if (!s_ui.initialized || !s_ui.running) {
        syslog(LOG_WARNING, "[%s] stream_begin: channel not ready\n", UI_TAG);
        return -ENODEV;
    }

    m = malloc(sizeof(*m));
    if (m == NULL) {
        return -ENOMEM;
    }
    m->user_text = NULL;
    if (user_text != NULL && user_text[0] != '\0') {
        m->user_text = strdup(user_text);
        if (m->user_text == NULL) {
            free(m);
            return -ENOMEM;
        }
    }

    pthread_mutex_lock(&s_stream_lock);
    s_stream.begun = true;            /* 重复 begin：LVGL 侧 reset 旧流 */
    s_stream.drop_logged = false;
    pthread_mutex_unlock(&s_stream_lock);

    if (lvgl_ui_post(stream_begin_async_cb, m) != 0) {
        free(m->user_text);
        free(m);
        pthread_mutex_lock(&s_stream_lock);
        s_stream.begun = false;
        pthread_mutex_unlock(&s_stream_lock);
        syslog(LOG_WARNING, "[%s] stream_begin: post failed\n", UI_TAG);
        return -ENOMEM;
    }
    return 0;
}

int lvgl_ui_channel_stream_delta(const char *delta_utf8)
{
    char *copy;

    if (delta_utf8 == NULL || delta_utf8[0] == '\0') {
        return 0;
    }

    pthread_mutex_lock(&s_stream_lock);
    if (!s_stream.begun) {
        bool log_it = !s_stream.drop_logged;

        s_stream.drop_logged = true;
        pthread_mutex_unlock(&s_stream_lock);
        if (log_it) {
            syslog(LOG_INFO,
                "[%s] stream delta without begin, ignored\n", UI_TAG);
        }
        return 0;
    }
    if (s_stream.pending_deltas >= STREAM_MAX_PENDING_DELTAS) {
        bool log_it = !s_stream.drop_logged;

        s_stream.drop_logged = true;
        pthread_mutex_unlock(&s_stream_lock);
        if (log_it) {
            syslog(LOG_WARNING,
                "[%s] stream delta backlog %d, dropping\n",
                UI_TAG, STREAM_MAX_PENDING_DELTAS);
        }
        return 0;
    }
    s_stream.pending_deltas++;
    pthread_mutex_unlock(&s_stream_lock);

    copy = strdup(delta_utf8);
    if (copy == NULL) {
        pthread_mutex_lock(&s_stream_lock);
        if (s_stream.pending_deltas > 0) {
            s_stream.pending_deltas--;
        }
        pthread_mutex_unlock(&s_stream_lock);
        return 0;                     /* 丢增量，end 仍然完整 */
    }

    if (lvgl_ui_post(stream_delta_async_cb, copy) != 0) {
        free(copy);
        pthread_mutex_lock(&s_stream_lock);
        if (s_stream.pending_deltas > 0) {
            s_stream.pending_deltas--;
        }
        pthread_mutex_unlock(&s_stream_lock);
        return 0;
    }
    return 0;
}

int lvgl_ui_channel_stream_end(const char *final_text, bool from_local)
{
    stream_end_msg_t *m;

    if (final_text == NULL) {
        final_text = "";
    }

    m = malloc(sizeof(*m));
    if (m == NULL) {
        return -ENOMEM;
    }
    m->final_text = strdup(final_text);
    m->from_local = from_local;
    if (m->final_text == NULL) {
        free(m);
        return -ENOMEM;
    }

    pthread_mutex_lock(&s_stream_lock);
    s_stream.begun = false;
    s_stream.pending_deltas = 0;   /* 旧的 delta 回调自减时会先判断 >0 */
    s_stream.drop_logged = false;
    pthread_mutex_unlock(&s_stream_lock);

    if (lvgl_ui_post(stream_end_async_cb, m) != 0) {
        free(m->final_text);
        free(m);
        syslog(LOG_WARNING, "[%s] stream_end: post failed\n", UI_TAG);
        return -ENOMEM;
    }
    return 0;
}

void lvgl_ui_channel_stream_abort(void)
{
    pthread_mutex_lock(&s_stream_lock);
    s_stream.begun = false;
    s_stream.pending_deltas = 0;
    s_stream.drop_logged = false;
    pthread_mutex_unlock(&s_stream_lock);

    if (lvgl_ui_post(stream_abort_async_cb, NULL) != 0) {
        syslog(LOG_WARNING, "[%s] stream_abort: post failed\n", UI_TAG);
    }
}

/* ── Chat history export (BLE `chat_history`) ──────────────────
 *
 * 历史环只在 LVGL 线程上读写（history_add() 由 posted 回调在 render 线程
 * 执行），所以导出必须把活干在 LVGL 线程：post 一个回调，调用线程用信号量
 * 最多等 200ms。BLE 的 chat_history 命令走这条路。
 *
 * ★ 为什么结果先落本文件的静态缓冲，再由调用方拷走：
 *   等待超时（render 线程卡住/还没起来）时，已经 post 出去的回调**之后**
 *   仍会被执行。假如它直接写调用方的栈缓冲，那一刻调用方早就返回了 ——
 *   一次 use-after-free。写自己的静态缓冲就没有悬垂指针：迟到的回调最多
 *   多生成一份同样合法的快照（取的是当前最新的历史）。
 */

#define HIST_EXPORT_BUF 1600  /* 与 BLE 单帧上限对齐（ble_gatt.c TX_SLOT_SIZE） */
#define HIST_WAIT_MS    200

static pthread_mutex_t s_hist_lock = PTHREAD_MUTEX_INITIALIZER;

static struct
{
    sem_t  done;
    bool   sem_ready;
    char   buf[HIST_EXPORT_BUF + 1];  /* 回调写入的 items JSON 数组文本 */
    size_t cap;                       /* 本次预算（含结尾 NUL） */
    int    max_items;
    int    items;                     /* 回调写入的条数 */
} s_hist_export;

/* JSON 字符串转义：引号/反斜杠/换行/回车/制表/其它控制字符转义，中文等
 * 非 ASCII 原样按 UTF-8 输出（98 号文要求）。按**整字符**截断，避免把
 * UTF-8 撕成半个。返回写入（dst 为 NULL 时为需要）的字节数，不写 NUL。
 *
 * 与 infra/ble_cmd_handler.c 里的同名实现故意各留一份：两边各管一个方向的
 * 文本，谁也不用把对方拉成依赖。 */
static size_t json_escape(char *dst, size_t cap, const char *src)
{
    const unsigned char *p = (const unsigned char *)src;
    size_t n = 0;

    if (src == NULL) {
        return 0;
    }

    while (*p != '\0') {
        unsigned char c = *p;
        char tmp[8];
        size_t need;
        size_t clen;

        /* 只为整字符截断，不校验 UTF-8 合法性 */
        if (c < 0x80) {
            clen = 1;
        } else if ((c & 0xE0) == 0xC0) {
            clen = 2;
        } else if ((c & 0xF0) == 0xE0) {
            clen = 3;
        } else if ((c & 0xF8) == 0xF0) {
            clen = 4;
        } else {
            clen = 1;
        }

        switch (c) {
            case '"':  memcpy(tmp, "\\\"", 2); need = 2; break;
            case '\\': memcpy(tmp, "\\\\", 2); need = 2; break;
            case '\n': memcpy(tmp, "\\n", 2);  need = 2; break;
            case '\r': memcpy(tmp, "\\r", 2);  need = 2; break;
            case '\t': memcpy(tmp, "\\t", 2);  need = 2; break;
            default:
                if (c < 0x20) {
                    snprintf(tmp, sizeof(tmp), "\\u%04x", (unsigned)c);
                    need = 6;
                } else {
                    need = clen;  /* 原样（含多字节 UTF-8） */
                }
                break;
        }

        if (need > cap - n) { /* 按**剩余**空间判断，不能用原始 cap */
            break;
        }
        if (dst != NULL) {
            memcpy(dst + n, (need == clen) ? (const char *)p : tmp, need);
        }
        n += need;
        p += clen;
    }

    return n;
}

/* 一条历史 -> {"u":<0|1>,"t":"<escaped>"}。
 * 返回写入字节数（含结尾 NUL 之前的字符数），放不下返回 0。 */
static size_t hist_item_build(char *dst, size_t cap, const char *text,
                              bool is_user, bool first)
{
    size_t n = 0;

    /* 空对象 ,{"u":1,"t":""} 需要 16 字节（含 NUL），比它还小的预算没有意义 */
    if (dst == NULL || cap < 16) {
        return 0;
    }

    if (!first) {
        dst[n++] = ',';
    }

    n += (size_t)snprintf(dst + n, cap - n, "{\"u\":%d,\"t\":\"",
                          is_user ? 1 : 0);
    if (n + 3 > cap) {   /* 至少留 '"'、'}' 和 NUL */
        return 0;
    }

    /* 留 3 字节给 '"'、'}' 和 NUL */
    n += json_escape(dst + n, cap - n - 3, text);
    if (n + 3 > cap) {
        return 0;
    }

    dst[n++] = '"';
    dst[n++] = '}';
    dst[n] = '\0';
    return n;
}

/* 组装 items 数组文本（旧→新）。只能在 LVGL 线程调用。返回条数。 */
static int hist_export_build(char *out, size_t cap, int max_items)
{
    char text[MSG_MAX_LEN];
    bool is_user;
    size_t budget;
    size_t used = 0;
    size_t n = 0;
    int total;
    int keep = 0;
    int emitted = 0;
    int i;

    if (out == NULL || cap < 32) {
        return -EINVAL;
    }
    out[0] = '\0';

    total = lvgl_ui_history_count();
    if (total <= 0) {
        return 0;
    }

    if (max_items <= 0 || max_items > total) {
        max_items = total;
    }
    if (max_items > CHAT_HISTORY_MAX) {
        max_items = CHAT_HISTORY_MAX;
    }

    budget = cap - 1;   /* 结尾 NUL */

    /* 第一遍：从**最新**往旧量长度，只保留放得下的那一段。手机要看的
     * 是最近的对话，历史太长时应当丢最旧的几条，而不是把最新的截掉。 */
    for (i = 0; i < max_items; i++) {
        size_t need;

        if (!lvgl_ui_history_get(i, text, sizeof(text), &is_user)) {
            break;
        }
        /* {"u":0,"t":""} 固定 14 字节；除第一条外还有 1 字节逗号 */
        need = json_escape(NULL, (size_t)-1, text) + 14 + (i > 0 ? 1 : 0);
        if (used + need > budget) {
            break;
        }
        used += need;
        keep++;
    }

    if (keep == 0) {
        /* 连最新一条都放不下：给它一条**截断**的版本，总比回空数组好 */
        if (!lvgl_ui_history_get(0, text, sizeof(text), &is_user)) {
            return 0;
        }
        return (hist_item_build(out, cap, text, is_user, true) > 0) ? 1 : 0;
    }

    /* 第二遍：keep 条里最旧的先输出（旧→新）。返回值取**实际写出**的
     * 条数 —— 调用方拿到的数量必须和 items 内容一致。 */
    for (i = keep - 1; i >= 0; i--) {
        size_t len;

        if (!lvgl_ui_history_get(i, text, sizeof(text), &is_user)) {
            break;
        }
        len = hist_item_build(out + n, cap - n, text, is_user, n == 0);
        if (len == 0) {
            break;
        }
        n += len;
        emitted++;
    }

    return emitted;
}

static void hist_export_async_cb(void *data)
{
    (void)data;

    s_hist_export.items = hist_export_build(s_hist_export.buf,
                                            s_hist_export.cap,
                                            s_hist_export.max_items);
    sem_post(&s_hist_export.done);
}

int lvgl_ui_history_export(char *out, size_t cap, int max_items)
{
    struct timespec ts;
    size_t take;
    int items;

    if (out == NULL || cap < 32) {
        return -EINVAL;
    }
    out[0] = '\0';

    if (!s_ui.initialized || !s_ui.running) {
        /* 没有 render 线程就没人能安全读历史环 */
        return -ENODEV;
    }

    pthread_mutex_lock(&s_hist_lock);

    if (!s_hist_export.sem_ready) {
        if (sem_init(&s_hist_export.done, 0, 0) != 0) {
            pthread_mutex_unlock(&s_hist_lock);
            return -ENOMEM;
        }
        s_hist_export.sem_ready = true;
    }

    /* 丢掉上一次（可能超时了）残留的完成信号，避免这次提前返回旧快照 */
    while (sem_trywait(&s_hist_export.done) == 0) {
    }

    s_hist_export.cap = (cap < sizeof(s_hist_export.buf))
                            ? cap : sizeof(s_hist_export.buf);
    s_hist_export.max_items = max_items;
    s_hist_export.items = -1;

    if (lvgl_ui_post(hist_export_async_cb, NULL) != 0) {
        pthread_mutex_unlock(&s_hist_lock);
        return -ENOMEM;
    }

    clock_gettime(CLOCK_REALTIME, &ts);
    ts.tv_nsec += HIST_WAIT_MS * 1000 * 1000;
    if (ts.tv_nsec >= 1000000000) {
        ts.tv_sec++;
        ts.tv_nsec -= 1000000000;
    }

    if (sem_timedwait(&s_hist_export.done, &ts) != 0) {
        /* 超时：render 线程没在 200ms 内跑到。迟到的回调只会刷新本文件的
         * 静态缓冲，不会再碰调用方的 out —— 安全。 */
        pthread_mutex_unlock(&s_hist_lock);
        return -ETIMEDOUT;
    }

    items = s_hist_export.items;
    if (items < 0) {
        pthread_mutex_unlock(&s_hist_lock);
        return -EIO;
    }

    take = strlen(s_hist_export.buf);
    if (take >= cap) {
        take = cap - 1;
    }
    memcpy(out, s_hist_export.buf, take);
    out[take] = '\0';

    pthread_mutex_unlock(&s_hist_lock);
    return items;
}
