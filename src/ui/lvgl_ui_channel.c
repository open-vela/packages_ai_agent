/* Thread-safe wrapper: lvgl_ui_channel_send() runs on the agent
 * (outbound dispatch) thread, so the lv_timer_create must be posted. */
static void pet_back_idle_after(uint32_t ms)
{
    pet_idle_req_t *req = malloc(sizeof(*req));
    if (req == NULL) {
        return;
    }
    req->ms = ms;
    if (lvgl_ui_post(pet_back_idle_post_cb, req) != 0) {
        free(req);
    }
}

/* ── Async message passing (agent threads -> LVGL thread) ──────── */

typedef struct {
    char text[MSG_MAX_LEN];
    bool is_user;
} ui_msg_t;

/* ── Cross-thread LVGL posting ────────────────────────────────────
 * LVGL is built with LV_OS_NONE here: no internal locking. Calling
 * lv_async_call() (which mutates the timer list) from agent/key/NSH
 * threads races with lv_timer_handler() on the render thread and can
 * corrupt the timer list -- observed as the render thread never waking
 * from usleep() again after an `ask` reply (Round 27 dumpstack).
 *
 * All non-render threads therefore enqueue {cb, data} under a mutex;
 * the render thread drains the queue each cycle and performs the
 * lv_async_call() itself. malloc/queue ops never touch LVGL state. */

typedef struct ui_post_node_s {
    lv_async_cb_t cb;
    void *data;
    struct ui_post_node_s *next;
} ui_post_node_t;

static pthread_mutex_t s_post_lock = PTHREAD_MUTEX_INITIALIZER;
static ui_post_node_t *s_post_head;
static ui_post_node_t *s_post_tail;
/* recycled nodes so a busy console does not churn the heap */
static ui_post_node_t *s_post_free;

int lvgl_ui_post(lv_async_cb_t cb, void *data)
{
    ui_post_node_t *n;

    if (cb == NULL) {
        return -1;
    }

    pthread_mutex_lock(&s_post_lock);
    n = s_post_free;
    if (n != NULL) {
        s_post_free = n->next;
    } else {
        n = malloc(sizeof(*n));
    }
    if (n == NULL) {
        pthread_mutex_unlock(&s_post_lock);
        return -1;
    }
    n->cb = cb;
    n->data = data;
    n->next = NULL;
    if (s_post_tail != NULL) {
        s_post_tail->next = n;
    } else {
        s_post_head = n;
    }
    s_post_tail = n;
    pthread_mutex_unlock(&s_post_lock);
    return 0;
}

/* Render thread only: drain pending posts. Runs before this cycle's
 * lv_timer_handler() so posted work lands in the same cycle it was
 * queued for whenever possible. */
static void ui_post_flush(void)
{
    ui_post_node_t *list;

    pthread_mutex_lock(&s_post_lock);
    list = s_post_head;
    s_post_head = NULL;
    s_post_tail = NULL;
    pthread_mutex_unlock(&s_post_lock);

    while (list != NULL) {
        ui_post_node_t *n = list;
        list = list->next;
        lv_async_call(n->cb, n->data);

        pthread_mutex_lock(&s_post_lock);
        n->next = s_post_free;
        s_post_free = n;
        pthread_mutex_unlock(&s_post_lock);
    }
}

/* Set the bubble text, truncated so the bubble stays short enough to
 * fully fit below the screen top edge. */
static void bubble_set_text(const char *text)
{
    char buf[BUBBLE_MAX_CHARS + 4];
    size_t len;
    size_t cut = BUBBLE_MAX_CHARS;

    if (text == NULL) {
        lv_label_set_text(s_ui.bubble_label, "");
        return;
    }
    len = strlen(text);
    if (len <= BUBBLE_MAX_CHARS) {
        lv_label_set_text(s_ui.bubble_label, text);
        return;
    }
    /* back off to a UTF-8 char boundary so the cut is clean */
    while (cut > 0 && ((unsigned char)text[cut] & 0xC0) == 0x80) {
        cut--;
    }
    memcpy(buf, text, cut);
    memcpy(buf + cut, "\xe2\x80\xa6", 4); /* … */
    lv_label_set_text(s_ui.bubble_label, buf);
}

static void bubble_update_async_cb(void *data)
{
    ui_msg_t *m = (ui_msg_t *)data;

    if (!s_ui.initialized || !s_ui.running) {
        free(m);
        return;
    }

    /* SPEED-B：流式 end 已经落过这条最终回答，dispatch 镜像不再重复落历史 */
    if (!stream_dedup_should_skip(m->text, m->is_user)) {
        history_add(m->text, m->is_user);
    }
    bubble_set_text(m->text);
    /* An agent reply -- including the proactive care messages -- that lands
     * while the user is still on the desktop brings the pet page up by
     * itself.  Both the text layer and the reply belong to that page, so
     * writing without entering would put the message where nobody sees it.
     * Runs on the LVGL thread (posted), which is what makes it safe here. */
    if (!m->is_user && ui_nav_current() == UI_PAGE_WATCHFACE) {
        /* 在表盘上收到 agent 回复 -> 自动切到 AI 页，否则这条消息
         * 落在没人看得见的地方。只在表盘时切，用户正在别的页面
         * 时不打断他。 */
        ui_nav_goto(UI_PAGE_AI);
    }
    /* AI reply text also lands in the pet page text layer (no-op when
     * the page is not open); user words never overwrite the greeting. */
    if (!m->is_user) {
        pet_page_update_response(m->text);
    }
    /* keep the launcher pet page bubble in sync (no-op when not created) */
    lv_obj_set_style_bg_color(s_ui.bubble,
                              m->is_user ? lv_color_hex(CLR_BUBBLE_USER)
                                         : lv_color_hex(CLR_BUBBLE_PET), 0);
    lv_obj_set_style_bg_color(s_ui.bubble_tail,
                              m->is_user ? lv_color_hex(CLR_BUBBLE_USER)
                                         : lv_color_hex(CLR_BUBBLE_PET), 0);

    /* Rebuild the history page list if it is open */
    if (s_ui.history_visible) {
        lv_obj_clean(s_ui.history_list);
        history_rebuild_list();
    }

    free(m);
}

/* ── Emotion helper (reply text -> pet emotion) ────────────────── */

static pet_emotion_t emotion_from_text(const char *text)
{
    if (text == NULL) {
        return PET_EMOTION_SPEAKING;
    }
    if (strstr(text, "？") || strstr(text, "?") ||
        strstr(text, "怎么") || strstr(text, "为什么")) {
        return PET_EMOTION_CONFUSED;
    }
    if (strstr(text, "哈哈") || strstr(text, "开心") ||
        strstr(text, "棒") || strstr(text, "爱") ||
        strstr(text, "❤")) {
        return PET_EMOTION_HAPPY;
    }
    return PET_EMOTION_SPEAKING;
}

