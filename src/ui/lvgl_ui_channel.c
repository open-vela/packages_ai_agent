/* ── Async message passing (agent threads -> LVGL thread) ──────── */

typedef struct {
    char text[MSG_MAX_LEN];
    bool is_user;
} ui_msg_t;

/* Set the bubble text, truncated so the bubble stays short enough to
 * fully fit below the screen top edge. */
static void bubble_set_text(const char *text)
{
    char buf[BUBBLE_MAX_CHARS + 4];
    size_t len;
    size_t cut = BUBBLE_MAX_CHARS;

    if (text == NULL) {
        lv_label_set_text(s_ui.bubble_label, "");
        return;
    }
    len = strlen(text);
    if (len <= BUBBLE_MAX_CHARS) {
        lv_label_set_text(s_ui.bubble_label, text);
        return;
    }
    /* back off to a UTF-8 char boundary so the cut is clean */
    while (cut > 0 && ((unsigned char)text[cut] & 0xC0) == 0x80) {
        cut--;
    }
    memcpy(buf, text, cut);
    memcpy(buf + cut, "\xe2\x80\xa6", 4); /* … */
    lv_label_set_text(s_ui.bubble_label, buf);
}

static void bubble_update_async_cb(void *data)
{
    ui_msg_t *m = (ui_msg_t *)data;

    if (!s_ui.initialized || !s_ui.running) {
        free(m);
        return;
    }

    history_add(m->text, m->is_user);
    bubble_set_text(m->text);
    /* AI reply text also lands in the pet page text layer (no-op when
     * the page is not open); user words never overwrite the greeting. */
    if (!m->is_user) {
        pet_page_update_response(m->text);
    }
    /* keep the launcher pet page bubble in sync (no-op when not created) */
    lv_obj_set_style_bg_color(s_ui.bubble,
                              m->is_user ? lv_color_hex(CLR_BUBBLE_USER)
                                         : lv_color_hex(CLR_BUBBLE_PET), 0);
    lv_obj_set_style_bg_color(s_ui.bubble_tail,
                              m->is_user ? lv_color_hex(CLR_BUBBLE_USER)
                                         : lv_color_hex(CLR_BUBBLE_PET), 0);

    /* Rebuild the history page list if it is open */
    if (s_ui.history_visible) {
        lv_obj_clean(s_ui.history_list);
        history_rebuild_list();
    }

    free(m);
}

/* ── Emotion helper (reply text -> pet emotion) ────────────────── */

static pet_emotion_t emotion_from_text(const char *text)
{
    if (text == NULL) {
        return PET_EMOTION_SPEAKING;
    }
    if (strstr(text, "？") || strstr(text, "?") ||
        strstr(text, "怎么") || strstr(text, "为什么")) {
        return PET_EMOTION_CONFUSED;
    }
    if (strstr(text, "哈哈") || strstr(text, "开心") ||
        strstr(text, "棒") || strstr(text, "爱") ||
        strstr(text, "❤")) {
        return PET_EMOTION_HAPPY;
    }
    return PET_EMOTION_SPEAKING;
}

/* ── Bubble show/hide ──────────────────────────────────────────── */

static void bubble_hide_anim_cb(lv_anim_t *a)
{
    lv_obj_add_flag(s_ui.bubble, LV_OBJ_FLAG_HIDDEN);
    s_ui.bubble_visible = false;
    (void)a;
}

static void bubble_show_anim(void)
{
    lv_obj_remove_flag(s_ui.bubble, LV_OBJ_FLAG_HIDDEN);
    lv_anim_t a;

    lv_anim_init(&a);
    lv_anim_set_var(&a, s_ui.bubble);
    lv_anim_set_exec_cb(&a, (lv_anim_exec_xcb_t)lv_obj_set_y);
    lv_anim_set_values(&a, BUBBLE_TOP_Y + 8, BUBBLE_TOP_Y);
    lv_anim_set_time(&a, 260);
    lv_anim_set_path_cb(&a, lv_anim_path_ease_out);
    lv_anim_start(&a);

    s_ui.bubble_visible = true;
}

static void bubble_hide_anim(void)
{
    lv_anim_t a;

    lv_anim_init(&a);
    lv_anim_set_var(&a, s_ui.bubble);
    lv_anim_set_exec_cb(&a, (lv_anim_exec_xcb_t)lv_obj_set_y);
    lv_anim_set_values(&a, BUBBLE_TOP_Y, BUBBLE_TOP_Y - 10);
    lv_anim_set_time(&a, 200);
    lv_anim_set_path_cb(&a, lv_anim_path_ease_in);
    lv_anim_set_deleted_cb(&a, bubble_hide_anim_cb);
    lv_anim_start(&a);
}

/* ── History page ──────────────────────────────────────────────── */

static lv_obj_t *history_bubble_create(lv_obj_t *parent, const char *text,
                                       bool is_user)
{
    lv_obj_t *row = lv_obj_create(parent);
    lv_obj_set_size(row, lv_pct(100), LV_SIZE_CONTENT);
    lv_obj_set_style_bg_opa(row, LV_OPA_TRANSP, 0);
    lv_obj_set_style_border_width(row, 0, 0);
    lv_obj_set_style_pad_all(row, 4, 0);
    lv_obj_set_flex_flow(row, is_user ? LV_FLEX_FLOW_ROW : LV_FLEX_FLOW_ROW_REVERSE);
    lv_obj_set_flex_align(row, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START);

    lv_obj_t *b = lv_obj_create(row);
    lv_obj_set_size(b, LV_SIZE_CONTENT, LV_SIZE_CONTENT);
    lv_obj_set_style_radius(b, BUBBLE_RADIUS, 0);
    lv_obj_set_style_bg_color(b, lv_color_hex(is_user ? CLR_BUBBLE_USER
                                                      : CLR_BUBBLE_PET), 0);
    lv_obj_set_style_border_width(b, 0, 0);
    lv_obj_set_style_pad_all(b, 0, 0);
    lv_obj_set_style_pad_left(b, BUBBLE_PAD_X, 0);
    lv_obj_set_style_pad_right(b, BUBBLE_PAD_X, 0);
    lv_obj_set_style_pad_top(b, BUBBLE_PAD_Y, 0);
    lv_obj_set_style_pad_bottom(b, BUBBLE_PAD_Y, 0);

    lv_obj_t *lbl = lv_label_create(b);
    lv_label_set_text(lbl, text);
    lv_label_set_long_mode(lbl, LV_LABEL_LONG_WRAP);
    lv_obj_set_width(lbl, BUBBLE_MAX_W - 2 * BUBBLE_PAD_X);
    lv_obj_set_style_text_font(lbl, s_ui.font, 0);
    lv_obj_set_style_text_color(lbl, lv_color_hex(CLR_TEXT), 0);
    lv_obj_set_style_text_line_space(lbl, 2, 0);

    return row;
}

static void history_rebuild_list(void)
{
    int i;
    int idx = s_history.head;
    chat_msg_t *m;

    if (!s_ui.history_list) {
        return;
    }

    lv_obj_clean(s_ui.history_list);
    for (i = 0; i < s_history.count; i++) {
        idx = (idx + CHAT_HISTORY_MAX - 1) % CHAT_HISTORY_MAX;
        m = &s_history.msgs[idx];
        history_bubble_create(s_ui.history_list, m->text, m->is_user);
    }
    lv_obj_scroll_to_y(s_ui.history_list, LV_COORD_MAX, LV_ANIM_OFF);
}

static void history_page_toggle(void)
{
    if (s_ui.history_visible) {
        lv_obj_add_flag(s_ui.history_page, LV_OBJ_FLAG_HIDDEN);
        s_ui.history_visible = false;
        return;
    }
    history_rebuild_list();
    lv_obj_move_foreground(s_ui.history_page);
    lv_obj_remove_flag(s_ui.history_page, LV_OBJ_FLAG_HIDDEN);
    s_ui.history_visible = true;
}

/* ── Pet tap: toggle the head bubble ───────────────────────────── */

static void pet_click_cb(lv_event_t *e)
{
    (void)e;

    if (s_ui.bubble_visible) {
        bubble_hide_anim();
        pet_display_set_emotion(PET_EMOTION_IDLE);
    } else {
        if (!s_ui.welcome_shown) {
            bubble_set_text(
                "\xe4\xbd\xa0\xe5\xa5\xbd\xe5\x91\x80\xef\xbc\x8c\xe6\x88\x91"
                "\xe6\x98\xaf\xe5\xb0\x8f\xe4\xba\x91\xef\xbc\x8c\xe7\x82\xb9"
                "\xe5\x87\xbb\xe6\x88\x91\xe5\xbc\x80\xe5\xa7\x8b\xe8\xaf\xb4"
                "\xe8\xaf\x9d\xef\xbd\x9e"); /* 你好呀，我是小云，点击我开始说话～ */
            s_ui.welcome_shown = true;
        }
        bubble_show_anim();
        pet_display_set_emotion(PET_EMOTION_ACTIVE);
        pet_back_idle_after(700);
    }
}

