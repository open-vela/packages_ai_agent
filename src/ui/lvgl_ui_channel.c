int lvgl_ui_channel_send_kind(const char *text, uint8_t kind)
{
    pet_emotion_t emotion;
    int ret;

    ret = queue_agent_bubble(text);
    if (ret != 0) {
        return ret;
    }

    /* emotion follows the reply content */
    emotion = emotion_from_text(text);

    /* P2a: 只有最终回答出声。状态语/错误语照旧上屏(气泡+历史)，但不进 TTS:
     * 显示了不等于要念，这是显示与播报的解耦点。 */
    if (kind != AGENT_MSG_KIND_FINAL) {
        pet_display_set_emotion(emotion == PET_EMOTION_SPEAKING
            ? PET_EMOTION_THINKING : emotion);
        pet_back_idle_after(1500);
        syslog(LOG_INFO, "[%s] no TTS for kind=%u\n", UI_TAG, (unsigned)kind);
        return 0;
    }

    /* ★ 2026-11-01 修复"有些回复没声音"：
     * 旧逻辑里只有 emotion == SPEAKING 才 TTS —— 而 emotion_from_text()
     * 会把含"？/怎么/为什么"的句子判成 CONFUSED、含"哈哈/开心/棒/爱"的
     * 判成 HAPPY，于是这些**最终回答只上屏不朗读**（真机实测：带问号的
     * 解释、带开心词的回复全都没声音）。
     * 表情只是表演，播报只由 kind 决定：FINAL 一律念。显示与播报解耦。 */
    pet_display_set_emotion(emotion == PET_EMOTION_SPEAKING
                            ? PET_EMOTION_SPEAKING : emotion);
    pet_back_idle_after(emotion == PET_EMOTION_SPEAKING ? 4000 : 1500);

    /* TTS 会阻塞数秒~数十秒(网络+解码+播放), 绝不能占住 LVGL 线程 ——
     * 之前这里同步调用导致"屏幕卡死"。改为后台线程念。 */
    if (voice_channel_speak_async(text) != 0) {
        syslog(LOG_WARNING, "[%s] speak async dispatch failed\n", UI_TAG);
    }

    return 0;
}

