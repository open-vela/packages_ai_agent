/* ── Chat history ring buffer ──────────────────────────────────── */

typedef struct {
    char text[MSG_MAX_LEN];
    bool is_user;
} chat_msg_t;

typedef struct {
    chat_msg_t msgs[CHAT_HISTORY_MAX];
    int head;
    int count;
} chat_history_t;

static chat_history_t s_history;

static void history_add(const char *text, bool is_user)
{
    chat_msg_t *slot = &s_history.msgs[s_history.head];

    memset(slot, 0, sizeof(*slot));
    strncpy(slot->text, text, MSG_MAX_LEN - 1);
    slot->text[MSG_MAX_LEN - 1] = '\0';
    slot->is_user = is_user;

    s_history.head = (s_history.head + 1) % CHAT_HISTORY_MAX;
    if (s_history.count < CHAT_HISTORY_MAX) {
        s_history.count++;
    }
}

int lvgl_ui_history_count(void)
{
    return s_history.count;
}

bool lvgl_ui_history_get(int newest_first, char *buf, size_t len,
                        bool *is_user)
{
    const chat_msg_t *m;
    int idx;

    /* Callers run on the LVGL thread (pet page, history page), the same
     * thread history_add() is reached from via lv_async_call, so the ring
     * needs no lock. */

    if (!buf || len == 0 || newest_first < 0 ||
        newest_first >= s_history.count) {
        return false;
    }

    idx = (s_history.head - 1 - newest_first + 2 * CHAT_HISTORY_MAX)
          % CHAT_HISTORY_MAX;
    m = &s_history.msgs[idx];

    strncpy(buf, m->text, len - 1);
    buf[len - 1] = '\0';
    if (is_user) {
        *is_user = m->is_user;
    }
    return true;
}

